#!/usr/bin/env python3
"""zulip_emoji_table: build preprocessor/chat/zulip_emoji_names.py, the
table of Slack emoji shortcodes that Zulip spells differently.

The LLM writes Slack shortcodes from Slack's whole vocabulary, so a
converter that knows only the names the repo happens to use shows the
rest as literal text. This joins Slack's names (the emoji-datasource
package, the data set Slack itself uses) to the Zulip server's own
emoji_codes.json on the code point, and writes every Slack name the
server does not know, mapped to the server's name for the same emoji. A
name the server already knows is left out even when Slack means a
different emoji by it, so no key is a Zulip name and converting a
converted message changes nothing. Runs as the owner; the server comes from
the owner's chat settings (ea_config.get_chat). Rerun it after a Zulip
upgrade, then scripts/zulip_emoji_check.py.

    scripts/zulip_emoji_table.py [--site https://host:8443] [--datasource 16.0.0]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "preprocessor"))
import ea_config  # noqa: E402

OUT = ROOT / "preprocessor" / "chat" / "zulip_emoji_names.py"
SLACK_DATA = "https://cdn.jsdelivr.net/npm/emoji-datasource@{version}/emoji.json"


def _codepoints(entry: dict) -> list[str]:
    """The entry's code points in Zulip's spelling, most exact first."""
    out = []
    for key in ("unified", "non_qualified"):
        cp = (entry.get(key) or "").lower()
        for cand in (cp, cp.replace("-fe0f", "")):
            if cand and cand not in out:
                out.append(cand)
    return out


def build(zulip: dict, slack: list[dict]) -> tuple[dict[str, str], list[str]]:
    """({Slack name: Zulip name}, [Slack names with no Zulip emoji])."""
    known, canonical = zulip["name_to_codepoint"], zulip["codepoint_to_name"]
    table: dict[str, str] = {}
    unmatched: list[str] = []
    for entry in slack:
        target = next((canonical[c] for c in _codepoints(entry) if c in canonical), None)
        for name in entry.get("short_names") or []:
            if name in known:
                continue
            if target is None:
                unmatched.append(name)
            else:
                table[name] = target
    return dict(sorted(table.items())), sorted(unmatched)


def render(table: dict[str, str], zulip_version: str, datasource: str) -> str:
    lines = [
        '"""Slack emoji shortcodes that Zulip spells differently, each mapped to',
        "the Zulip name for the same emoji. Generated by scripts/zulip_emoji_table.py",
        f"from Zulip {zulip_version} and emoji-datasource {datasource}; rebuild it with",
        "that script rather than editing it. A name Zulip knows is not a key, so",
        'converting twice changes nothing."""',
        "",
        "SLACK_TO_ZULIP = {",
    ]
    lines += [f"    {k!r}: {v!r}," for k, v in table.items()]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--site")
    ap.add_argument("--datasource", default="16.0.0", help="emoji-datasource version")
    a = ap.parse_args()
    site = (a.site or ea_config.get_chat()["zulip"]["site"]).rstrip("/")
    zulip = requests.get(f"{site}/static/generated/emoji/emoji_codes.json", timeout=30).json()
    version = requests.get(f"{site}/api/v1/server_settings", timeout=30).json().get("zulip_version", "?")
    slack = requests.get(SLACK_DATA.format(version=a.datasource), timeout=60).json()
    table, unmatched = build(zulip, slack)
    OUT.write_text(render(table, version, a.datasource))
    print(f"wrote {len(table)} names to {OUT.relative_to(ROOT)}")
    print(f"{len(unmatched)} Slack name(s) with no Zulip emoji: {' '.join(unmatched) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
